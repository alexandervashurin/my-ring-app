SELECT '=== ЦЕХА ===' AS '';
SELECT COUNT(*) as 'Всего цехов', COUNT(*) * 10 as 'Примерное кол-во работников' FROM Цех;

SELECT '=== РАБОТНИКИ ===' AS '';
SELECT COUNT(*) as 'Всего работников' FROM Работник;

SELECT '=== ПО КАТЕГОРИЯМ ===' AS '';
SELECT к.название_категории, COUNT(r.id) as 'Кол-во'
FROM Категория_работника к
LEFT JOIN Работник r ON r.категория_работника_id = к.id
GROUP BY к.id;

SELECT '=== ПО ЦЕХАМ ===' AS '';
SELECT ц.название_цеха, COUNT(r.id) as 'Кол-во'
FROM Цех ц
LEFT JOIN Работник r ON r.цех_id = ц.id
GROUP BY ц.id
ORDER BY COUNT(r.id) DESC;

SELECT '=== ЗАРПЛАТЫ (диапазоны) ===' AS '';
SELECT 
    CASE 
        WHEN n.общая_зарплата < 30000 THEN 'Менее 30 000 ₽'
        WHEN n.общая_зарплата BETWEEN 30000 AND 50000 THEN '30 000 - 50 000 ₽'
        WHEN n.общая_зарплата BETWEEN 50001 AND 80000 THEN '50 000 - 80 000 ₽'
        WHEN n.общая_зарплата BETWEEN 80001 AND 120000 THEN '80 000 - 120 000 ₽'
        ELSE 'Более 120 000 ₽'
    END as 'Диапазон',
    COUNT(*) as 'Кол-во работников'
FROM Начисление_заработной_платы n
JOIN Учет_рабочего_времени у ON n.учет_рабочего_времени_id = у.id
WHERE у.год = 2025 AND у.месяц = 10
GROUP BY 1
ORDER BY MIN(n.общая_зарплата);

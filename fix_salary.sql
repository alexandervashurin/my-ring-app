-- Исправление начислений зарплаты для всех работников
-- Файл: fix_salary.sql

-- Удаляем существующие начисления (кроме первых 8 оригинальных)
DELETE FROM Начисление_заработной_платы WHERE id > 8;

-- Удаляем существующий учёт времени (кроме первых 8 оригинальных)  
DELETE FROM Учет_рабочего_времени WHERE id > 8;

-- Генерируем учёт времени для всех работников (id > 8)
INSERT INTO Учет_рабочего_времени 
(работник_id, год, месяц, всего_часов_за_месяц_по_плану, всего_часов_в_месяц_по_факту, 
 количество_отработанных_дней, количество_рабочих_часов_в_день, всего_отработанных_часов, 
 сколько_должны_отработать, больничные_дни, командировочные_дни)
SELECT 
    r.id,
    2025,
    10,
    160,
    CASE 
        WHEN r.категория_работника_id IN (5, 6) THEN 120 + (r.id % 40)
        WHEN r.категория_работника_id = 8 THEN 140 + (r.id % 20)
        WHEN r.система_оплаты_id = 3 THEN 170 + (r.id % 30)
        ELSE 155 + (r.id % 20)
    END,
    CASE 
        WHEN r.категория_работника_id IN (5, 6) THEN 15 + (r.id % 5)
        WHEN r.категория_работника_id = 8 THEN 18 + (r.id % 3)
        ELSE 19 + (r.id % 3)
    END,
    8,
    CASE 
        WHEN r.категория_работника_id IN (5, 6) THEN 120 + (r.id % 40)
        WHEN r.категория_работника_id = 8 THEN 140 + (r.id % 20)
        WHEN r.система_оплаты_id = 3 THEN 170 + (r.id % 30)
        ELSE 155 + (r.id % 20)
    END,
    160,
    CASE WHEN r.id % 7 = 0 THEN 2 ELSE 0 END,
    CASE WHEN r.id % 11 = 0 THEN 1 ELSE 0 END
FROM Работник r
WHERE r.id > 8;

-- Генерируем начисления зарплаты с подзапросами
INSERT INTO Начисление_заработной_платы 
(учет_рабочего_времени_id, год, месяц, зарплата_за_больничные_дни, 
 зарплата_за_командировочные_дни, общая_зарплата)
SELECT 
    у.id,
    у.год,
    у.месяц,
    0,  -- больничные упростим
    0,  -- командировочные упростим
    CASE 
        WHEN r.система_оплаты_id = 1 THEN  -- Оклад
            COALESCE((SELECT оклад_в_месяц FROM Оклад WHERE id = r.оклад_id), 35000) 
            * (у.всего_отработанных_часов * 1.0 / у.сколько_должны_отработать)
        WHEN r.система_оплаты_id = 2 THEN  -- Почасовая
            COALESCE((SELECT ставка_в_час FROM Почасовые_ставки WHERE id = r.почасовая_ставка_id), 250) 
            * у.всего_отработанных_часов
        WHEN r.система_оплаты_id = 3 THEN  -- Сдельная
            (у.всего_отработанных_часов * 280) + (у.всего_отработанных_часов * 70)
        WHEN r.система_оплаты_id = 4 THEN  -- Проектная
            45000 + (у.всего_отработанных_часов * 120)
        ELSE 35000
    END
FROM Учет_рабочего_времени у
JOIN Работник r ON у.работник_id = r.id
WHERE у.id > 8;

-- Проверка результатов
SELECT '=== ВСЕГО РАБОТНИКОВ ===' AS '';
SELECT COUNT(*) FROM Работник;

SELECT '=== ВСЕГО ЗАПИСЕЙ УЧЁТА ВРЕМЕНИ ===' AS '';
SELECT COUNT(*) FROM Учет_рабочего_времени;

SELECT '=== ВСЕГО НАЧИСЛЕНИЙ ЗАРПЛАТЫ ===' AS '';
SELECT COUNT(*) FROM Начисление_заработной_платы;

SELECT '=== ЗАРПЛАТЫ ПО ДИАПАЗОНАМ ===' AS '';
SELECT 
    CASE 
        WHEN n.общая_зарплата < 30000 THEN 'Менее 30 000 ₽'
        WHEN n.общая_зарплата BETWEEN 30000 AND 50000 THEN '30 000 - 50 000 ₽'
        WHEN n.общая_зарплата BETWEEN 50001 AND 80000 THEN '50 000 - 80 000 ₽'
        WHEN n.общая_зарплата BETWEEN 80001 AND 120000 THEN '80 000 - 120 000 ₽'
        ELSE 'Более 120 000 ₽'
    END as 'Диапазон',
    COUNT(*) as 'Кол-во'
FROM Начисление_заработной_платы n
JOIN Учет_рабочего_времени у ON n.учет_рабочего_времени_id = у.id
WHERE у.год = 2025 AND у.месяц = 10
GROUP BY 1
ORDER BY MIN(n.общая_зарплата);

SELECT '=== МИН/МАКС/СРЕДНЯЯ ЗАРПЛАТА ===' AS '';
SELECT 
    MIN(общая_зарплата) as 'Минимум',
    MAX(общая_зарплата) as 'Максимум',
    ROUND(AVG(общая_зарплата), 2) as 'Средняя'
FROM Начисление_заработной_платы n
JOIN Учет_рабочего_времени у ON n.учет_рабочего_времени_id = у.id
WHERE у.год = 2025 AND у.месяц = 10;

SELECT '=== ПО КАТЕГОРИЯМ РАБОТНИКОВ ===' AS '';
SELECT к.название_категории, COUNT(r.id) as 'Кол-во'
FROM Категория_работника к
LEFT JOIN Работник r ON r.категория_работника_id = к.id
GROUP BY к.id;

SELECT '=== ТОП-5 ПО ЗАРПЛАТЕ ===' AS '';
SELECT r.фамилия, r.имя, ц.название_цеха, n.общая_зарплата
FROM Начисление_заработной_платы n
JOIN Учет_рабочего_времени у ON n.учет_рабочего_времени_id = у.id
JOIN Работник r ON у.работник_id = r.id
LEFT JOIN Цех ц ON r.цех_id = ц.id
WHERE у.год = 2025 AND у.месяц = 10
ORDER BY n.общая_зарплата DESC
LIMIT 5;

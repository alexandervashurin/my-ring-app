-- 11. НАЧИСЛЕНИЕ ЗАРАБОТНОЙ ПЛАТЫ
-- ============================================================================

-- Генерация начислений для всех работников
INSERT INTO Начисление_заработной_платы (учет_рабочего_времени_id, год, месяц, зарплата_за_больничные_дни, зарплата_за_командировочные_дни, общая_зарплата)
SELECT 
    у.id,
    у.год,
    у.месяц,
    CASE WHEN у.больничные_дни > 0 THEN 
        CASE 
            WHEN r.система_оплаты_id = 1 THEN (о.оклад_в_месяц / 22) * у.больничные_дни * 0.8
            WHEN r.система_оплаты_id = 2 THEN п.ставка_в_час * 8 * у.больничные_дни * 0.8
            ELSE 5000
        END
    ELSE 0 END,
    CASE WHEN у.командировочные_дни > 0 THEN 
        CASE 
            WHEN r.система_оплаты_id = 1 THEN (о.оклад_в_месяц / 22) * у.командировочные_дни
            WHEN r.система_оплаты_id = 2 THEN п.ставка_в_час * 8 * у.командировочные_дни
            ELSE 7000
        END
    ELSE 0 END,
    CASE 
        WHEN r.система_оплаты_id = 1 THEN  -- Оклад
            о.оклад_в_месяц * (у.всего_отработанных_часов * 1.0 / у.сколько_должны_отработать)
            + CASE WHEN у.больничные_дни > 0 THEN (о.оклад_в_месяц / 22) * у.больничные_дни * 0.8 ELSE 0 END
            + CASE WHEN у.командировочные_дни > 0 THEN (о.оклад_в_месяц / 22) * у.командировочные_дни ELSE 0 END
        WHEN r.система_оплаты_id = 2 THEN  -- Почасовая
            п.ставка_в_час * у.всего_отработанных_часов
            + CASE WHEN у.больничные_дни > 0 THEN п.ставка_в_час * 8 * у.больничные_дни * 0.8 ELSE 0 END
            + CASE WHEN у.командировочные_дни > 0 THEN п.ставка_в_час * 8 * у.командировочные_дни ELSE 0 END
        WHEN r.система_оплаты_id = 3 THEN  -- Сдельная
            (у.всего_отработанных_часов * 250) + (у.всего_отработанных_часов * 50)  -- База + премия
        WHEN r.система_оплаты_id = 4 THEN  -- Проектная
            45000 + (у.всего_отработанных_часов * 100)
        ELSE 35000
    END
FROM Учет_рабочего_времени у
JOIN Работник r ON у.работник_id = r.id
LEFT JOIN Оклад о ON r.оклад_id = о.id
LEFT JOIN Почасовые_ставки п ON r.почасовая_ставка_id = п.id
WHERE у.id > 8;  -- Не дублировать существующие

